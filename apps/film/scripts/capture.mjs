import { createRequire } from "node:module";
import fs from "node:fs/promises";
const require = createRequire(new URL("../../web/package.json", import.meta.url));
const { chromium } = require("playwright");
const base = process.env.POT_CAPTURE_URL || "http://127.0.0.1:3001";
const output = new URL("../public/screens/", import.meta.url);
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 }, deviceScaleFactor: 2, reducedMotion: "reduce" });
await page.goto(base);
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: new URL("home-raw.png", output).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
await page.locator(".product-preview-card").screenshot({ path: new URL("trip-card.png", output).pathname.replace(/^\/(\w:)/, "$1") });
await page.getByRole("button", { name: "A gift", exact: true }).click();
await page.locator(".product-preview-card").screenshot({ path: new URL("gift-card.png", output).pathname.replace(/^\/(\w:)/, "$1") });
await page.getByRole("button", { name: "A good cause", exact: true }).click();
await page.locator(".product-preview-card").screenshot({ path: new URL("community-card.png", output).pathname.replace(/^\/(\w:)/, "$1") });
await page.setViewportSize({ width: 1600, height: 2200 });
await page.goto(`${base}/create?template=trip`);
await page.getByLabel("Pot name").waitFor();
await page.locator("#pot-deadline").fill("2027-02-12T18:00");
await page.locator(".pot-mode-fieldset").screenshot({ path: new URL("rules.png", output).pathname.replace(/^\/(\w:)/, "$1") });
await page.evaluate(() => window.scrollTo(0, 0));
const formBox = await page.locator(".pot-create-form").boundingBox();
await page.screenshot({ path: new URL("plan-fields.png", output).pathname.replace(/^\/(\w:)/, "$1"), clip: { x: formBox.x, y: formBox.y, width: formBox.width, height: 470 } });
await page.getByRole("button", { name: "Preview this plan" }).click();
await page.evaluate(() => window.scrollTo(0, 0));
const preview = await page.locator(".pot-create-preview").boundingBox();
const details = await page.locator(".pot-create-preview-details").boundingBox();
await page.screenshot({ path: new URL("plan-summary.png", output).pathname.replace(/^\/(\w:)/, "$1"), clip: { x: preview.x, y: preview.y, width: preview.width, height: details.y + details.height - preview.y + 6 } });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(base);
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: new URL("mobile-hero.png", output).pathname.replace(/^\/(\w:)/, "$1"), clip: { x: 0, y: 0, width: 390, height: 490 } });
await browser.close();
console.log("Captured actual product states and measured editorial crops. No transaction data was fabricated.");
